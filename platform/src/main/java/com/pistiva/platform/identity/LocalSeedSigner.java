package com.pistiva.platform.identity;

import com.pistiva.platform.common.Ed25519;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.PrivateKey;
import java.security.PublicKey;
import java.util.Map;

/**
 * The signing key held in the platform's memory, from a configured seed or (development only) a
 * seed file generated on first start. Production deployments should prefer a KMS-backed signer.
 */
public class LocalSeedSigner implements PlatformSigner {

    private static final Logger log = LoggerFactory.getLogger(LocalSeedSigner.class);

    private final PrivateKey privateKey;
    private final PublicKey publicKey;
    private final String kid;
    private final String source;

    public LocalSeedSigner(String seedOrSecret, String seedFile) throws IOException {
        String seed = seedOrSecret;
        String from = "configured seed";
        if (seed == null || seed.isBlank()) {
            seed = loadOrCreateSeed(Path.of(seedFile));
            from = "seed file " + Path.of(seedFile).toAbsolutePath();
        }
        seed = normalizeSeed(seed.trim());
        this.privateKey = Ed25519.privateKeyFromSeed(seed);
        this.publicKey = Ed25519.publicKeyFromSeed(seed);
        this.kid = PlatformSigner.kidFor(publicKey);
        this.source = from;
    }

    @Override
    public String currentKid() {
        return kid;
    }

    @Override
    public byte[] sign(byte[] data) {
        return Ed25519.sign(privateKey, data);
    }

    @Override
    public Map<String, PublicKey> verificationKeys() {
        return Map.of(kid, publicKey);
    }

    @Override
    public String describe() {
        return "local key from " + source;
    }

    /**
     * Accepts a base64url 32-byte Ed25519 seed as is. Any other secret (for example a random value
     * generated by a hosting provider) is turned into a seed with SHA-256, so the key stays stable
     * for as long as the secret does.
     */
    static String normalizeSeed(String secret) {
        try {
            if (Ed25519.b64urlDecode(secret).length == 32) {
                return secret;
            }
        } catch (IllegalArgumentException e) {
            // not base64url: derive below
        }
        if (secret.length() < 32) {
            throw new IllegalStateException("Signing key secret must be at least 32 characters");
        }
        try {
            return Ed25519.b64url(MessageDigest.getInstance("SHA-256").digest(secret.getBytes(StandardCharsets.UTF_8)));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    private static String loadOrCreateSeed(Path file) throws IOException {
        if (Files.exists(file)) {
            return Files.readString(file, StandardCharsets.US_ASCII);
        }
        log.warn("No signing key configured; generating a development key at {}", file.toAbsolutePath());
        String seed = Ed25519.rawPrivateSeed(Ed25519.generate().getPrivate());
        if (file.getParent() != null) {
            Files.createDirectories(file.getParent());
        }
        Files.writeString(file, seed, StandardCharsets.US_ASCII);
        return seed;
    }
}
